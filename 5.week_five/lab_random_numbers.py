import random

# A random float between 0 and 1 using random.random().
print(f"Random float between 0 and 1: {random.random()}")

# A random integer from 1 to 6 (simulate a dice roll) using random.randint().
print(f"Random integer from 1 to 6: {random.randint(1, 6)}")

# A random integer between 10 and 20 using random.randrange().
print(f"Random integer between 10 and 20: {random.randrange(10, 21)}")