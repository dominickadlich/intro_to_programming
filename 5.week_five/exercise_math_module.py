import math

num = float(input("Choose any number: "))

# The square root using math.sqrt().
print(f"Square root of {num}: {math.sqrt(num)}")

# The ceiling and floor values using math.ceil() and math.floor().
print(f"Ceiling of {num}: {math.ceil(num)}")
print(f"Floor of {num}: {math.floor(num)}")

# The absolute value using math.fabs().
print(f"Absolute value of {num}: {math.fabs(num)}")

# π multiplied by 2.
print(f"Pi multiplied by 2: {math.pi * 2}")