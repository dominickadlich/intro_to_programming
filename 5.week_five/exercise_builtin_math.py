# abs() returns the absolute value of a number
print(f"Absolute value of -17: {abs(-17)}")

# max() returns largest of its arguments
print(f"Largest number: {max(8, -3, 12)}")

# min() returns smallest of its arguments
print(f"Smallest number: {min(8, -3, 12)}")

# pow() raises the first argument to the power of the second
print(f"5 cubed: {pow(5, 3)}")

# round() rounds a number to the given number of decimal places
print(f"4.8765 rounded to 2 decimals: {round(4.8765, 2)}")