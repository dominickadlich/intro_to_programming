# Objective:
# Use a for loop to traverse a list and calculate the total sum.

# Start with the following list:
numbers = [12, 45, 23, 67, 34, 89]

# Initialize a variable total to 0.
total = 0

# Use a for loop to add each number in the list to total.
for num in numbers:
    total += num

# After the loop, display the total sum.
print(f"The total sum is: {total}")

# Expected Result:
# The total sum is: 270